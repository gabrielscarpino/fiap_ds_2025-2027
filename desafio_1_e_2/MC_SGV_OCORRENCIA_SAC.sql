SELECT CP.CD_CATEGORIA,CP.TP_CATEGORIA,CP.DS_CATEGORIA,CP.DT_INICIO,CP.DT_TERMINO,CP.ST_CATEGORIA, 
COUNT(SAC.NR_SAC) AS TOTAL_CHAMADOS
FROM MC_CATEGORIA_PROD CP LEFT JOIN MC_PRODUTO PRO
    ON CP.CD_CATEGORIA = PRO.CD_CATEGORIA 
    LEFT JOIN MC_SGV_SAC SAC
    ON PRO.CD_PRODUTO = SAC.CD_PRODUTO
GROUP BY CP.CD_CATEGORIA,CP.TP_CATEGORIA,CP.DS_CATEGORIA,CP.DT_INICIO, CP.DT_TERMINO, CP.ST_CATEGORIA
ORDER BY CD_CATEGORIA;

    